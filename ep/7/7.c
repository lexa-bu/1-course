/* Задача:
https://ivtipm.github.io/Programming/Glava07/index07.htm#z190 (ctrl + ЛКМ)
7. 269д
Даны целые числаa a_{1},..., a_{n} (в этой последовательности могут быть повторяющиеся члены).
Выяснить, сколько чисел входит в последовательность более чем по одному разу.
Учтено: Количество символов не вводить.
Последовательность символов вводить как строку с неизвестным заранее n (n<256).

Автор: Булдыгеров Алексей
*/

// включение модулей (библиотек)
#include <stdio.h>
#include <locale.h>
#include <stdlib.h>

#define ARR_MAX 256

// главная функция программы
int main()
{
    // поддержка кириллицы
    setlocale(LC_ALL, "");
    char input[ARR_MAX];                         // массив для хранения входной строки
    int numbers[ARR_MAX];                        // массив для хранения чисел
    int n = 0;                                   // количество считанных чисел
    int pos = 0;                                 // позиция в строке
    int duplicate = 0;                           // количество повторяющихся чисел
    
    puts("Введите числа (через пробел):");       // ввод данных
    scanf("%255[^\n]", input);                   // читаем строку
    
    while (pos < ARR_MAX && input[pos] != '\0' && n < ARR_MAX)  // вытаскиваем числа из строки
    {
        while (input[pos] == ' ' || input[pos] == '\t')
            pos++;

        if (input[pos] == '\0')                  // дошли до конца - заканчиваем
            break;
        int num = 0;                             // переменная для сборки самого числа
        int sign = 1;                            // знак числа (1 для плюса, -1 для минуса)
    
if (input[pos] == '-')                           // проверка на отрицательность числа
        {
            sign = -1;
            pos++;
        }
        while (input[pos] >= '0' && input[pos] <= '9')  // собираем число из цифр
        {
            num = num * 10 + (input[pos] - '0'); // математический сдвиг на разряд и добавление цифры
            pos++;
        }
        numbers[n] = num * sign;                 // сохраняем итоговое число в массив с правильным знаком
        n++;                                     // увеличиваем счетчик найденных чисел
    }

    for (int i = 0; i < n; i++)                  // ищем сколько чисел встречается > 1 раза
    {
        int already_seen = 0;                    // проверка на подсчет считанного числа (чтобы не посчитать 2 раза)
        for (int j = 0; j < i; j++)
        {
            if (numbers[i] == numbers[j])
            {
                already_seen = 1;
                break;
            }
        }

        if (already_seen == 0)                   // если это число мы видим впервые - ищем его копии дальше по массиву
        {
            int count = 1;
            for (int k = i + 1; k < n; k++)
            {
                if (numbers[i] == numbers[k])
                {
                    count++;
                }
            }
            if (count > 1)                       // если число встречается в массиве больше одного раза - увеличиваем счетчик ответа
            {
                duplicate++;
            }
        }
    }
    // вывод результата
    printf("Ответ: Найдено %d повторяющихся чисел.\n", duplicate);
    return 0;
}