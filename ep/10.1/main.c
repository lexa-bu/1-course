/**
 * @file main.c
 * @author Булдыгеров Алексей
 * @example Задание № 10.1 (480а). 
 * Дан файл f, компоненты которого являются целыми числами. Получить в файле g
 * все компоненты файла f: являющиеся четными числами.
 * @note Не использовать массивы или списки.
 * @link https://ivtipm.github.io/Programming/Glava13/index13.htm#z480
 * @test Создается файл "f.txt", куда записываются данные. 
 * ./название_компилируемого_файла
 * Проверяются данные и исключаются все символы / числа, кроме чётных.
 * чётные записываются в файл "g.txt" (создается автоматически) и автоматически
 * открывается Блокнот с этим файлом.
 */

// включение модулей (библиотек)
#include <stdio.h>
#include <stdlib.h>
#include <locale.h>

/**
 * @brief Основная функция программы
 */
int main(void)
{
    // поддержка кириллицы
    setlocale(LC_ALL, "");
    // переменная для чтения
    int number;
    // входной файл
    FILE *f = fopen("f.txt", "r");
    // выходной файл
    FILE *g = fopen("g.txt", "w");
    
    // проверка успешного открытия файлов
    if (!f || !g) {
        printf("Ошибка открытия файла!\n");
        if (f) fclose(f);
        if (g) fclose(g);
        return 1;
    }

    // читаем числа из файла f пока не конец файла
    while (!feof(f)) 
    {
        if (fscanf(f, "%d", &number) == 1) 
        {
            // проверка на четность
            if (number % 2 == 0) 
            {
                fprintf(g, "%d\n", number); // запись в файл g
            }
        } 
        else 
        {
            if (!feof(f)) 
            {
                fgetc(f); 
            }
        }
    }
    // закрываем файлы и освобождаем ресурсы
    fclose(f);
    fclose(g);
    // уведомление пользователя и автоматический просмотр результата
    printf("Готово! Чётные числа записаны в файл g.txt и был автоматически открыт с помощью Блокнот.\n");
    system("notepad g.txt");
    return 0;
}